# =============================================================================
# demos/langgraph_argus.py — 用 LangGraph 实现 Argus
#
# 【学习目标】
#   理解 LangGraph 的图结构思维，对比 OpenAI SDK 的声明式风格。
#   LangGraph 把 Agent 的执行流程显式定义成一张"图"。
#
# 【什么是图（Graph）？】
#   图 = 节点（Node）+ 边（Edge）
#   节点 = 一个处理步骤（如"分析代码"）
#   边   = 步骤之间的流转关系（如"分析完了去输出"）
#   复杂 Agent 可以有分支、循环、并行等图结构。
#
# 【与 openai_argus.py 的对比】
#   openai_argus.py  声明式，框架隐藏了流程细节
#   langgraph_argus  显式定义每个节点和状态，流程一目了然
#
# 【运行要求】
#   pip install langgraph
#   需要配置好 llm 变量（本文件中未定义，实际使用时替换）
# =============================================================================

from langgraph.graph import StateGraph
from typing import TypedDict


# =============================================================================
# 定义状态（State）
# 【说明】
#   LangGraph 要求显式定义"状态"——Agent 在执行过程中需要传递和更新的数据。
#   TypedDict 是 Python 的类型提示，定义字典的字段和类型。
#
#   这里的状态很简单，只有两个字段：
#     diff    - 输入：要审查的代码变更
#     review  - 输出：审查结果
#
#   每个节点接收当前状态，处理后返回更新后的状态（部分字段）。
# =============================================================================
class ReviewState(TypedDict):
    diff: str     # 输入：代码变更
    review: str   # 输出：审查结果（初始为空，由 reason 节点填充）


# =============================================================================
# 定义节点（Node）
# 【说明】
#   节点 = 一个处理函数，接收当前状态，返回状态的更新部分。
#   这里只有一个节点 reason，负责调用 LLM 分析代码。
#
#   参数：state - 当前状态字典
#   返回：包含要更新的字段的字典（只需包含变化的部分）
# =============================================================================
def reason(state: ReviewState) -> ReviewState:
    """
    【节点说明】
    推理节点：调用 LLM 分析 diff，生成审查结果。

    对应 PRA 循环中的 R（Reasoning）步骤。
    """
    # #A 调用 LLM 分析代码
    # 【说明】
    #   llm.invoke 是 LangChain 风格的 LLM 调用方式。
    #   state['diff'] 从当前状态中取出 diff 内容。
    #   返回的 review 会更新到状态的 review 字段。
    review = llm.invoke(f"Review: {state['diff']}")
    return {"review": review}


# =============================================================================
# 构建图（Graph）
# 【说明】
#   分三步：定义图 → 添加节点 → 设置入口 → 编译
# =============================================================================

# 第一步：创建状态图，指定状态类型
graph = StateGraph(ReviewState)

# 第二步：添加节点（节点名, 处理函数）
# 【说明】节点名是字符串标识符，用于定义边时引用
graph.add_node("review", reason)

# 第三步：设置入口节点（从哪里开始执行）
graph.set_entry_point("review")

# 第四步：编译成可运行的 Agent
# 【说明】compile() 把图定义转换成可执行的对象，
# 之后就可以用 agent.invoke({"diff": "..."}) 来运行了
agent = graph.compile()

