# =============================================================================
# demos/openai_argus.py — 用 OpenAI Agents SDK 实现 Argus
#
# 【学习目标】
#   理解同一个 Argus 功能用不同框架怎么写，对比 OpenAI SDK 的风格。
#   OpenAI Agents SDK 是声明式的，代码极其简洁。
#
# 【与 core.py 的对比】
#   core.py         手动调用 Anthropic API，自己处理请求/响应
#   openai_argus.py 用框架封装，框架帮你管理循环和工具调用
#
# 【运行要求】
#   pip install openai-agents
#   export OPENAI_API_KEY=sk-...
#   需要把 sample.diff 文件放在运行目录下
# =============================================================================

from agents import Agent, Runner

# =============================================================================
# 创建 Argus Agent
# 【说明】
#   OpenAI Agents SDK 的核心抽象：Agent = 角色定义 + 模型选择
#   不需要自己写循环，框架会自动处理多轮对话和工具调用。
#
#   参数说明：
#     name         - Agent 的名字，方便日志和调试识别
#     instructions - 系统提示，定义这个 Agent 的角色和行为
#     model        - 使用的模型，这里用 GPT-4.1
# =============================================================================
argus = Agent(
    name="Argus",
    instructions="You are an expert code reviewer. Analyze diffs for bugs.",
    model="gpt-4.1",
)

if __name__ == "__main__":
    # -------------------------------------------------------------------------
    # 读取要审查的 diff 文件
    # 【说明】
    #   实际使用时把要审查的代码变更保存成 sample.diff 文件，
    #   运行前确保文件在当前目录下。
    # -------------------------------------------------------------------------
    diff = open("sample.diff").read()

    # -------------------------------------------------------------------------
    # 同步运行 Agent，等待结果
    # 【说明】
    #   Runner.run_sync - 同步运行，阻塞直到 Agent 完成任务
    #   第一个参数是 Agent 实例，第二个是用户的输入消息
    #   框架会自动管理循环：LLM 推理 → 工具调用 → 继续推理 → 直到完成
    # -------------------------------------------------------------------------
    result = Runner.run_sync(argus, f"Review this diff:\n{diff}")

    # final_output 是 Agent 最终给出的文字答案
    print(result.final_output)

