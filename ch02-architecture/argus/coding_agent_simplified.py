# =============================================================================
# argus/coding_agent_simplified.py — 带循环的 Agent（概念性代码，不可独立运行）
#
# 【学习目标】
#   理解真正的 Agent 和 core.py 的区别：
#   core.py 只走一次 PRA，这里有 while True 循环，
#   LLM 自己决定什么时候任务完成。
#
# 【注意】
#   这是概念性伪代码，ReadFile/EditFile/ConversationHistory 等类
#   在本文件中未定义，无法直接运行。用于理解结构，不用于执行。
# =============================================================================


class CodingAgent:
    """
    【类说明】
    一个可以操作文件、执行命令的编码 Agent。
    用户给它一个任务（如"帮我重构这个函数"），
    它会循环调用工具，直到任务完成。
    """

    def __init__(self):
        # ---------------------------------------------------------------------
        # #A 工具箱：Agent 能使用的所有工具
        # 【说明】
        #   工具是 Agent 与外部世界交互的手段。
        #   没有工具，Agent 只能"说"，不能"做"。
        #   这里列出的工具：
        #     ReadFile  - 读取文件内容
        #     EditFile  - 修改文件
        #     Bash      - 执行 shell 命令
        #     Search    - 全文搜索
        #     Glob      - 按文件名模式匹配（如 *.py）
        #     Grep      - 在文件中搜索文本
        # ---------------------------------------------------------------------
        self.tools = [
            ReadFile, EditFile, Bash,
            Search, Glob, Grep
        ]

        # ---------------------------------------------------------------------
        # #B 记忆：保存完整的对话历史
        # 【说明】
        #   LLM 本身是无状态的，每次调用都是独立的。
        #   ConversationHistory 把所有历史消息存起来，
        #   每轮循环都把完整历史传给 LLM，让它"记得"之前做了什么。
        # ---------------------------------------------------------------------
        self.memory = ConversationHistory()

    def run(self, user_task: str):
        """
        【方法说明】
        接收用户任务，循环执行 PRA，直到完成。

        参数：
            user_task - 用户的自然语言指令，如"帮我重构 utils.py 里的 parse 函数"
        """
        # 把用户任务存入记忆，作为对话的起点
        self.memory.add_user_message(user_task)

        # =====================================================================
        # 核心循环：真正的 Agent 精髓所在
        # 【说明】
        #   这个 while True 就是 PRA 循环的体现。
        #   每一轮：感知 → 推理 → 行动 → 更新记忆 → 下一轮感知...
        #   直到 LLM 认为任务完成，返回最终答案，才 break 出去。
        #
        #   和 core.py 的区别：
        #   core.py 只调用一次 LLM 就结束（适合简单的单步任务）
        #   这里会多轮调用，适合需要多步操作的复杂任务
        # =====================================================================
        while True:

            # -----------------------------------------------------------------
            # P — 感知：从记忆中取出当前上下文
            # #C 【说明】
            #   get_context_window() 返回的是"当前 LLM 能看到的所有内容"，
            #   包括用户的原始任务、之前所有工具调用的结果等。
            #   "上下文窗口"是有长度限制的，超出部分会被截断或压缩。
            # -----------------------------------------------------------------
            context = self.memory.get_context_window()

            # -----------------------------------------------------------------
            # R — 推理：LLM 决定下一步做什么
            # #D 【说明】
            #   LLM 看到所有历史后，会决定：
            #     a) 我需要调用某个工具（继续循环）
            #     b) 我已经完成了，给出最终答案（退出循环）
            # -----------------------------------------------------------------
            response = self.llm.generate(context)

            # LLM 说"我完成了"，返回最终结果，结束循环
            if response.is_final_answer():
                return response.text

            # -----------------------------------------------------------------
            # A — 行动：调用 LLM 选择的工具
            # #E 【说明】
            #   LLM 在 response 里指定了要调用哪个工具、传什么参数，
            #   execute_tool 负责真正执行这个工具调用并返回结果。
            # -----------------------------------------------------------------
            tool_result = self.execute_tool(response.tool)

            # -----------------------------------------------------------------
            # 更新记忆：把工具结果存入历史
            # #F 【说明】
            #   工具结果存入记忆后，下一轮循环 LLM 就能看到这次行动的结果，
            #   从而决定下一步做什么。这就是"反馈"形成闭环的机制。
            # -----------------------------------------------------------------
            self.memory.add_tool_result(tool_result)
        # 循环继续，回到 P — 感知...
